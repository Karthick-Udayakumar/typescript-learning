//Data type = Type of Data

//1. Primitive Datatype - Memory is fixed - predefined data type
//number - any kind of number - int, float, byte, short
//string
//boolean - true or false
//BigInt
//undefined
//null

//2. Non Primitive Datatype/ Reference Type - Memory is not fixed
//Array
//Objects
//functions
//map/list/set

//To declare any variables -There are 3 identifiers - var, const, let

//1. number

let x = 10;
console.log(x);
console.log(typeof x);

let y = 22.22;
console.log(y);
console.log(typeof y)

//2. String

let name = "Karthick"
console.log(name);
console.log(typeof name);

let m1 = "$"
console.log(m1);
console.log(typeof m1);

let m2 = '1000'
console.log(typeof m2);

//undefined
let p;
console.log(typeof p);

//3. Boolean
let flag = true;
console.log(typeof flag);


//4. Undefined
let firstName = undefined;
console.log(typeof firstName);
firstName = "Karthick"
console.log(typeof firstName);

//5.  Null
let obj = null
console.log(obj)
console.log(typeof obj)

//Reinitialization
let c = 10;
c = 20;
console.log(c)

//var
var i = 20;
var i = 10;
console.log(i);

//constant 

const myName = 'Karthick'
myName = 'Rohit'
console.log(myName)

