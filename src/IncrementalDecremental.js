//Post Increment

let a = 1
let b = a++

console.log(a)
console.log(b)

let num = 10
console.log(num++)
console.log(num)

//Pre Increment

let m = 1;
let n = ++m
console.log(n)
console.log(++m)

let u = -1000
let y = ++u
console.log(u) //-1000 + 1 = -999
console.log(y) //-999

//post decrement
let w = 2
let r = w--
console.log(w) //1
console.log(r) //2

//Pre decrement
let s = 2
let c = --s
console.log(s) //1
console.log(c) //1

let pop = 10
console.log(++pop)
console.log(pop)

let rest = -9
console.log(--rest) //-10
console.log(rest) //-10

